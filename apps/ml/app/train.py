"""
Offline training entry point for the FinLeaf ML service.

    python -m app.train              # train only if artefacts are missing
    python -m app.train --force      # retrain from scratch
    python app/train.py --force      # same thing, invoked as a script

Training happens here, never inside a request. This script fits the trust
models and the anomaly detector, writes every artefact into MODEL_DIR
(default: ../models), and prints a readable summary of what it did.

The metrics it prints are measured on a held-out slice of SYNTHETIC data
(see app/training_data.py). They describe how well the models recover a rule we
wrote ourselves. They are not a performance claim about real borrowers, and
this summary says so out loud so nobody screenshots it and forgets.
"""

import argparse
import logging
import os
import sys
import textwrap

# Allow `python app/train.py` as well as `python -m app.train`: as a script,
# sys.path[0] is app/ rather than its parent, so `app` is not importable until
# the parent directory is put back on the path.
if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app import models as ml  # noqa: E402  (import after the path fix above)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m app.train",
        description="Train the FinLeaf trust and anomaly models and write their artefacts.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="retrain even if artefacts already exist",
    )
    parser.add_argument(
        "--model-dir",
        default=ml.MODEL_DIR,
        help="where artefacts are written (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)-8s %(name)s: %(message)s",
    )

    if os.path.abspath(args.model_dir) != os.path.abspath(ml.MODEL_DIR):
        ml.MODEL_DIR = args.model_dir

    paths = ml.artefact_paths()
    already_trained = ml.artefacts_present() and os.path.exists(paths["metrics"])
    if already_trained and not args.force:
        print(
            f"Artefacts already present in {ml.MODEL_DIR}.\n"
            "Nothing to do. Re-run with --force to retrain from scratch."
        )
        return 0

    print(
        f"Retraining into {ml.MODEL_DIR} (--force)"
        if args.force
        else f"Training into {ml.MODEL_DIR}"
    )
    metrics = ml.train_models(force=True)

    print()
    print(_render_summary(metrics, ml.MODEL_DIR))
    return 0


def _render_summary(metrics: dict, model_dir: str) -> str:
    lines = ["Held-out metrics (synthetic hold-out set)", "-" * 58]

    for key, label in (("logistic_regression", "LogisticRegression"),
                       ("gradient_boosting", "HistGradientBoostingClassifier")):
        scores = metrics.get(key, {})
        lines.append(f"{label}")
        for name in ("accuracy", "precision", "recall", "auc_roc"):
            value = scores.get(name)
            lines.append(f"    {name:<10} {value:.4f}" if isinstance(value, (int, float))
                         else f"    {name:<10} n/a")
        lines.append("")

    detector = metrics.get("anomaly_detector", {})
    lines.append("IsolationForest (anomaly detector)")
    for name in ("n_normal_samples", "flagged_fraction", "contamination", "algorithm"):
        if name in detector:
            lines.append(f"    {name:<18} {detector[name]}")
    lines.append(f"    {'score_range':<18} {detector.get('score_range', 'n/a')}")
    lines.append("")

    for name in ("trained_at", "trained_on"):
        lines.append(textwrap.fill(f"{name}: {metrics.get(name, 'n/a')}", 58,
                                   subsequent_indent="    "))
    lines.append("")
    lines += [
        "Artefacts written to:",
        f"    {model_dir}",
        "",
        textwrap.fill(
            "These numbers were measured on SYNTHETIC data generated by "
            "app/training_data.py. The models are illustrative only: they have "
            "not been validated on real borrowers and must not be presented as "
            "though they have.",
            58,
        ),
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())