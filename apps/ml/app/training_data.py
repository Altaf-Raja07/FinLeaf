"""
SYNTHETIC TRAINING DATA - NOT REAL BORROWER DATA.

Everything in this module is generated by a seeded random number generator.
There is no dataset behind it, no real user, and no observed repayment
outcome. It exists because labelled behavioural data for Indian micro-lending
does not publicly exist: lenders hold it, it is proprietary, it is regulated,
and no open corpus of it can be redistributed or trained on.

WHAT THIS MEANS FOR THE MODELS
------------------------------
The population below is simulated from hand-picked distributions, and the
"repayment-worthy" label is produced by a latent scoring rule that we wrote
ourselves. A model fitted to it therefore learns *our assumptions*, not the
world. Its metrics measure how well it recovers a rule we already knew the
answer to - they are NOT evidence of performance on real borrowers.

Any model trained on this data is ILLUSTRATIVE ONLY. It must never be
presented to a user, a regulator, an investor or a lender as validated on real
borrowers, and it must not be used to make an actual credit decision about a
real person's money. Before any such use, replace this module with a training
pipeline fed by properly consented, lawfully held data, and re-run
`python -m app.train --force`.

Everything else about the data is deliberate:

  * No protected attributes (gender, religion, caste, age bracket, location)
    are generated or used as features, so the model cannot proxy-discriminate
    through them - mirroring the published fairness practice of dropping
    sensitive attributes and checking accuracy is unaffected.
  * Features are clipped to the same ranges the API accepts (see
    `app/features.py`), so the service is never asked to score a value the
    training pipeline would refuse to produce.
  * The generator is seeded, so training is reproducible: the same seed yields
    the same population, the same models and the same metrics on every machine.
"""

import numpy as np
import pandas as pd

# Re-exported so callers keep importing the feature list from here, where it
# has always lived. The definitions themselves live in app/features.py.
from .features import FEATURES, ANOMALY_FEATURES  # noqa: F401

__all__ = ["FEATURES", "ANOMALY_FEATURES", "generate", "generate_normal_transactions"]

N_USERS = 4000
SEED = 42

# Bounds applied to the raw (pre-normalisation) values so the normalised
# features the API accepts (0-1) are exactly the ones the model is fitted on.
MAX_AGE_DAYS = 365.0   # normalised by 365 -> at most 1.0
MAX_TXN_COUNT = 30.0   # normalised by 30  -> at most 1.0


def generate(n: int = N_USERS, seed: int = SEED) -> pd.DataFrame:
    """Return a synthetic population of borrowers with a synthetic label.

    `n` rows and `seed` control the draw; the columns are the FEATURES listed
    above plus `target` (1 = repayment-worthy under the latent rule below).
    """
    rng = np.random.default_rng(seed)

    # Correlated features: three archetypes dominate the population.
    archetype = rng.choice(3, size=n, p=[0.35, 0.40, 0.25])

    savings = np.clip(
        np.where(archetype == 0, rng.beta(7, 3, n),
                 np.where(archetype == 1, rng.beta(4, 4, n), rng.beta(2, 6, n))), 0, 1)
    bills = np.clip(
        np.where(archetype == 0, rng.beta(8, 2, n),
                 np.where(archetype == 1, rng.beta(5, 4, n), rng.beta(2, 5, n))), 0, 1)
    consistency = np.clip(
        np.where(archetype == 0, rng.beta(7, 3, n),
                 np.where(archetype == 1, rng.beta(4, 4, n), rng.beta(2, 7, n))), 0, 1)
    group = np.clip(rng.beta(3, 3, n) + np.where(archetype == 0, 0.25, 0), 0, 1)
    balance_stability = np.clip(rng.beta(5, 3, n), 0, 1)
    # Clipped to the API's normalised ceiling (see MAX_AGE_DAYS / MAX_TXN_COUNT).
    age_days = np.clip(
        np.where(archetype == 0, rng.gamma(3.0, 60, n),
                 np.where(archetype == 1, rng.gamma(2.0, 45, n), rng.gamma(1.2, 30, n))),
        5, MAX_AGE_DAYS)
    txn_count = np.clip(
        np.where(archetype == 0, rng.gamma(5, 4, n),
                 np.where(archetype == 1, rng.gamma(3, 4, n), rng.gamma(1.5, 3, n))),
        1, MAX_TXN_COUNT)
    repayment = np.where(archetype == 0, rng.beta(9, 2, n),
                         np.where(archetype == 1, rng.beta(4, 5, n), rng.beta(1, 5, n)))

    age_norm = age_days / 365.0
    txn_norm = txn_count / MAX_TXN_COUNT

    # Latent truth: weighted combination with one deliberate interaction term,
    # so a boosted tree has something to learn that plain linear LR cannot.
    latent = (
        2.6 * savings
        + 2.2 * bills
        + 1.4 * consistency
        + 1.1 * age_norm
        + 0.9 * group
        + 0.8 * balance_stability
        + 0.7 * txn_norm
        + 2.0 * repayment
        + 1.5 * savings * bills  # interaction: saving well only counts if you also pay bills
    )

    # Add noise, then threshold at the 45th percentile for ~55% positive class.
    noisy = latent + rng.normal(0, 0.45, n)
    threshold = np.percentile(noisy, 45)
    label = (noisy > threshold).astype(int)

    return pd.DataFrame({
        "savings_regularity": savings,
        "on_time_bill_ratio": bills,
        "txn_consistency": consistency,
        "account_age_days": age_norm,
        "group_activity": group,
        "avg_balance_stability": balance_stability,
        "monthly_txn_count": txn_norm,
        "repayment_history": repayment,
        "target": label,
    })


def generate_normal_transactions(seed: int = 7, n: int = 3000) -> np.ndarray:
    """A synthetic population of ordinary transactions, for fitting the
    IsolationForest. Deliberately free of labelled fraud: real fraud labels are
    not available, and the detector is unsupervised for exactly that reason.

    Columns follow ANOMALY_FEATURES. Values are clipped to the API's accepted
    ranges so the forest is never fitted outside the contract it is scored
    under - `category_rarity` in particular is a ratio and cannot be negative.
    """
    rng = np.random.default_rng(seed)
    amount_log = rng.normal(6.2, 0.9, n)
    hour = rng.choice(np.arange(6, 23), n, p=_hour_distribution(6, 23))
    rapid = np.clip(rng.beta(1.2, 9, n), 0, 1)
    new_cp = np.clip(rng.beta(0.7, 14, n), 0, 1)
    rarity = np.clip(rng.normal(0.3, 0.18, n), 0, 1)
    return np.column_stack([amount_log, hour, rapid, new_cp, rarity])


def _hour_distribution(start: int = 0, end: int = 24) -> np.ndarray:
    """More activity in the morning and evening than at 3am."""
    weights = np.array([
        1.0, 0.6, 0.3, 0.2, 0.3, 1.2, 2.6, 3.0, 2.4, 2.0, 2.1, 2.3,
        2.2, 2.0, 1.9, 2.0, 2.4, 3.0, 3.4, 3.0, 2.4, 1.8, 1.4, 0.9,
    ])
    sliced = weights[start:end]
    return sliced / sliced.sum()